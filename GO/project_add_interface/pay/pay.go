package pay

import "fmt"

type PaymentMethod interface { //интерфейс чтобы использовать разные банки, и каждый банк должен уметь проводить оплату и отмену оплаты
	Pay(rub int) int
	CancelPay(id int)
}

type Payment struct {
	PaymentInfo map[int]Info
	//сохранение информации об оплате, множества операций
	//1. массив -  но при добавлении новых операций, массив нельзя будет расширить
	//2. слайс x--x ужасный выбор, тк при сохранении огромного количества платежей, допустим миллион он будет проделывать миллион итераций, но там где нужен порядок, или например сортировка, слайсы будут использоваться в отличии от мапы
	//3. мапа --> мапа лучший выбор, тк не зависит от количества, тк поиск происходит по ключу

	paymentMethod PaymentMethod //в переменную paymentMethod мы сохраняем способ оплаты из нашего интерфейса
}

func NewPayment(paymentMethod PaymentMethod) *Payment { //создаем конструктор для безопасности, чтобы всегда создавалась мапа при новом платеже
	return &Payment{
		PaymentInfo:   make(map[int]Info),
		paymentMethod: paymentMethod, //в структуру сохраняем способ оплаты
	}
}

//Pay (платеж)
//принимает описание оплаты, что покупаем
//принимает сумму оплаты
//возвращает ID проведенной операции

func (p *Payment) Pay(name string, rub int) int {
	//1. принимает оплату
	//2. получается id оплаты
	id := p.paymentMethod.Pay(rub) //проводим операцию оплатф при помощи метода оплаты (интерфейса)
	info := Info{                  //собираем в структуру об информациях информацию об оплате
		Description: name,
		Rub:         rub,
		Canceled:    false, //только произвели оплату поэтому мы не успели ее отмениить
	}

	//3. сохраняет информацию об операции
	//--описание операции
	//--сколько потрачено
	//--отменена операция?
	p.PaymentInfo[id] = info

	//возвращается ID операции
	return id
}

//Cancel (Отмена операции)
//Принимает ID операции
//ничего не возвращает

func (p *Payment) CancelPay(id int) {

	info, ok := p.PaymentInfo[id]
	if !ok {
		fmt.Println("Такой операции не существует!")
		return
	}

	p.paymentMethod.CancelPay(id) //интерфейс только принимает оплату и отменяет, а какие операции до этого были он не помнит
	info.Canceled = true

	p.PaymentInfo[id] = info
}

//Info (информации об определенной операции)
//принимает ID операции
//возвращает информацию об операции (что куплено и на какую сумму)

func (p Payment) Info(id int) Info {
	info, ok := p.PaymentInfo[id]
	if !ok {
		return Info{}
	}

	return info
}

//AllInfo (вся информация)
//ничего не принимает
//возвращает информацию о всех операциях

func (p Payment) AllInfo() map[int]Info {
	tempmap := make(map[int]Info, len(p.PaymentInfo))

	for k, v := range p.PaymentInfo {
		tempmap[k] = v
	}

	return tempmap

	//мапа в Go работает как ссылка. Если бы мы просто написали return p.PaymentInfo, то
	//любой код снаружи мог бы случайно удалить или подделать записи в нашем журнале
	//Поэтому мы создаем новую пустую мапу tempmap, перекладываем туда все данные циклом и отдаем наружу безопасную копию.

	//мапа имеет также указатель на данные, если мы вернем мапу, то оно вернет копию мапы
	//которая указывает на оригинальные данные, через указатель кто то может получить доступ к оригинальным данным
	//поэтому мы создаем такую же мапу, но новую
	//перебираем значения старой мапы, и заносим их в новую временную мапу
	//а после возвращаем эту временную мапу
}
